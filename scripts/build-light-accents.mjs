// Generates src/app/light-accents.css.
//
// The bright accent text colours the UI uses (text-amber-400, text-green-400, ...) are tuned for the dark
// theme and nearly vanish on the light one (green-400 is 1.2:1 on a light panel). In the light theme each
// accent text class is remapped to the lightest shade of the same colour that stays readable.
//
//   node scripts/build-light-accents.mjs
//
// `src/lib/lightAccents.test.ts` fails if a class is used that this file does not cover, so rerun it after
// adding a new accent text colour.
import fs from 'fs';
import path from 'path';
import colors from 'tailwindcss/colors.js';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'src', 'app', 'light-accents.css');

/** Panels in the light theme sit on roughly this colour (page #f1f5f9 under nested tints); text must clear 5:1 on it. */
const SURFACE = [222, 226, 232];
const NEED = 5;

const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const lum = ([r, g, b]) => { const f = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); }; return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b); };
const ratio = (a, b) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };

/** The lightest shade (600 to 900) of a colour that clears NEED:1 on the light surface. */
function readableShade(name) {
  for (const shade of [600, 700, 800, 900]) {
    if (ratio(hex(colors[name][shade]), SURFACE) >= NEED) return shade;
  }
  return 900;
}

export const ACCENTS = ['amber', 'yellow', 'orange', 'green', 'emerald', 'lime', 'blue', 'sky', 'cyan', 'purple', 'violet', 'red', 'rose', 'pink', 'indigo', 'teal', 'fuchsia'];
/** text-<accent>-<200..600>, optionally with a variant prefix and an /alpha. */
export const CLASS_RE = new RegExp(`(?:(hover|group-hover|focus|active):)?text-(${ACCENTS.join('|')})-(200|300|400|500|600)(?:/(\\d+))?(?![\\w-])`, 'g');

function collect() {
  const found = new Map();
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) walk(p);
      else if (/\.(tsx?|css)$/.test(e.name) && !p.endsWith('light-accents.css')) {
        const text = fs.readFileSync(p, 'utf8');
        for (const m of text.matchAll(CLASS_RE)) found.set(m[0], { variant: m[1], color: m[2], alpha: m[4] });
      }
    }
  };
  walk(path.join(ROOT, 'src'));
  return found;
}

const esc = (cls) => cls.replace(/[:/]/g, (c) => `\\${c}`);

export function build() {
  const rules = [];
  for (const [cls, { variant, color, alpha }] of [...collect()].sort((a, b) => a[0].localeCompare(b[0]))) {
    const [r, g, b] = hex(colors[color][readableShade(color)]);
    const a = alpha ? Number(alpha) / 100 : null;
    const value = a === null ? `rgb(${r} ${g} ${b} / var(--tw-text-opacity, 1))` : `rgb(${r} ${g} ${b} / ${a})`;
    const pseudo = variant === 'hover' ? ':hover' : variant === 'focus' ? ':focus' : variant === 'active' ? ':active' : '';
    const sel = variant === 'group-hover' ? `.group:hover .${esc(cls)}` : `.${esc(cls)}${pseudo}`;
    rules.push(`[data-resolved='light'] ${sel} { color: ${value}; }`);
  }
  return `/* Generated by scripts/build-light-accents.mjs. Do not edit; rerun the script. */\n${rules.join('\n')}\n`;
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, '/')}` || process.argv[1]?.endsWith('build-light-accents.mjs')) {
  const css = build();
  fs.writeFileSync(OUT, css);
  console.log(`${css.split('\n').length - 2} light-theme accent rules -> src/app/light-accents.css`);
}
